import {expectedPhotography} from './clinic-photography-contract.mjs';
import {readFileSync,writeFileSync,mkdirSync,existsSync} from 'node:fs';
import {createRequire} from 'node:module';
import {createHash} from 'node:crypto';
import {dirname,resolve} from 'node:path';
const require=createRequire('C:/Users/Farhad/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/');
const sharp=require('sharp');
const groups=['services','journal-a','journal-b','environments'];
const expected={service:16,journal:23,environment:3};
const jobs=groups.flatMap(group=>{
 const path='docs/clinic-photography/'+group+'.json';
 if(!existsSync(path)) throw new Error('Missing completed generation batch: '+path);
 return JSON.parse(readFileSync(path,'utf8').replace(/^\uFEFF/,'')).jobs;
});
for(const [kind,slugs] of Object.entries(expectedPhotography)){
 const actual=jobs.filter(j=>j.kind===kind).map(j=>j.slug);
 if(actual.length!==slugs.length||new Set(actual).size!==slugs.length||!slugs.every(s=>actual.includes(s)))throw new Error('Incomplete or duplicated '+kind+' topic coverage.');
}
if(jobs.some(j=>j.id!==j.kind+'-'+j.slug))throw new Error('Job identity does not match its topic.');
if(new Set(jobs.map(j=>j.id)).size!==42)throw new Error('Missing or repeated asset IDs.');
const hash=path=>createHash('sha256').update(readFileSync(path)).digest('hex');
const maps={service:{},journal:{},environment:{}};
for(const job of jobs){
 if(!existsSync(job.original)||!job.review||job.concepts?.length!==3||!job.prompt||!job.alt)throw new Error('Incomplete reviewed job: '+job.id);
 const info=await sharp(job.original).metadata();
 const base='/media/clinic-photography-v1/'+job.kind+'/'+job.slug;
 const src=base+'.webp',thumbnail=base+'-800.webp';
 mkdirSync(dirname('public'+src),{recursive:true});
 let full;
 for(const quality of job.slug==='corridor'?[85,78,70,62]:[85]){
  full=await sharp(job.original).rotate().resize({width:1600,withoutEnlargement:true}).webp({quality,effort:6}).toFile('public'+src);
  if(job.slug!=='corridor'||full.size<=120*1024)break;
 }
 if(job.slug==='corridor'&&full.size>120*1024)throw new Error('Hero exceeds 120KB.');
 const thumb=await sharp(job.original).rotate().resize({width:800,withoutEnlargement:true}).webp({quality:82,effort:6}).toFile('public'+thumbnail);
 Object.assign(job,{src,thumbnail,width:full.width,height:full.height,thumbnailWidth:thumb.width,thumbnailHeight:thumb.height,originalWidth:info.width,originalHeight:info.height,bytes:full.size,thumbnailBytes:thumb.size,sha256:hash(job.original),webpSha256:hash('public'+src),thumbnailSha256:hash('public'+thumbnail),tool:'built-in image_gen'});
 maps[job.kind][job.slug]={src,thumbnail,alt:job.alt,width:full.width,height:full.height,thumbnailWidth:thumb.width,position:job.position||'50% 50%',caption:job.caption||'تصویر مفهومی ساخته‌شده با هوش مصنوعی؛ عکس بیمار یا نتیجه درمان نیست.'};
}
if(new Set(jobs.map(j=>j.sha256)).size!==42)throw new Error('A source photograph was reused across independent topics.');
writeFileSync('docs/clinic-photography/manifest.json',JSON.stringify({version:1,brand:'ELVITHA',generatedAt:new Date().toISOString(),tool:'built-in image_gen',expected,protectedBaseline:'docs/clinic-photography/protected-baseline.json',jobs},null,2)+'\n');
let output="// Generated by scripts/prepare-clinic-photography.mjs from reviewed batch manifests.\nimport type {JournalImage} from './journal-images';\n\n";
for(const [kind,name] of [['service','servicePhotography'],['journal','journalPhotography'],['environment','environmentPhotography']])output+='export const '+name+':Record<string,JournalImage> = '+JSON.stringify(maps[kind],null,2)+';\n\n';
writeFileSync('lib/clinic-photography.ts',output);
mkdirSync('output/playwright/clinic-photography',{recursive:true});
for(const kind of Object.keys(expected)){
 const subset=jobs.filter(j=>j.kind===kind);
 const cols=kind==='environment'?3:4,cellW=300,cellH=330;
 const composites=[];
 for(let i=0;i<subset.length;i++){
  const job=subset[i],x=(i%cols)*cellW,y=Math.floor(i/cols)*cellH;
  composites.push({input:await sharp('public'+job.src).resize(300,300,{fit:'cover'}).toBuffer(),left:x,top:y});
  const label='<svg width="300" height="30"><rect width="300" height="30" fill="#fbfaf8"/><text x="8" y="20" font-family="Arial" font-size="13" fill="#332f30">'+job.slug+'</text></svg>';
  composites.push({input:Buffer.from(label),left:x,top:y+300});
 }
 await sharp({create:{width:cols*cellW,height:Math.ceil(subset.length/cols)*cellH,channels:3,background:'#fbfaf8'}}).composite(composites).png().toFile('output/playwright/clinic-photography/'+kind+'-contact-sheet.png');
}
