import {chromium} from 'file:///C:/Users/Farhad/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
import {mkdirSync,writeFileSync} from 'node:fs';
mkdirSync('qa/portrait-turn',{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
const results=[],errors=[];
const origin=process.env.PORTRAIT_BASE_URL||'http://127.0.0.1:3000';
const check=(name,pass,detail)=>{results.push({name,pass,detail});if(!pass)console.error('FAIL',name,detail)};
const page=await browser.newPage({viewport:{width:1440,height:1000}});
page.on('pageerror',e=>errors.push(e.message));
await page.goto(origin+'/',{waitUntil:'networkidle'});
await page.waitForFunction(()=>document.querySelector('#main')?.dataset.openingState==='ready');
await page.waitForTimeout(1200);
const v=page.locator('[data-scrub-video=portrait]');
check('New portrait loaded and decoded',await v.evaluate(e=>e.dataset.mediaState==='ready'&&e.readyState>=2&&e.dataset.src.includes('portrait-turn')));
const seek=async progress=>{await page.evaluate(p=>{const el=document.querySelector('#understanding');scrollTo({top:el.offsetTop+(el.offsetHeight-innerHeight)*p,behavior:'instant'})},progress);await page.waitForTimeout(900);return v.evaluate(e=>e.currentTime)};
const early=await seek(.13);
await page.screenshot({path:'qa/portrait-turn/desktop-cheek.png'});
const mid=await seek(.5);
await page.screenshot({path:'qa/portrait-turn/desktop-lip.png'});
const later=await seek(.87);
await page.screenshot({path:'qa/portrait-turn/desktop-jaw.png'});
check('Scroll advances through all callout phases',await page.locator('.face-analysis').getAttribute('data-phase')==='2',{early,mid,later});
const lateX=await page.locator('[data-face-marker="1"] circle').first().getAttribute('cx');
const back=await seek(.1);
const earlyX=await page.locator('[data-face-marker="1"] circle').first().getAttribute('cx');
check('Film and facial anchors reverse with scroll',back<later-2&&Number(lateX)>Number(earlyX)+50,{back,later,lateX,earlyX});
check('Delivery contains 180 frames over 7.5 seconds',await v.evaluate(e=>Math.abs(e.duration-7.5)<.05));
check('Annotation matches video aspect ratio',await page.locator('.portrait-film').evaluate(e=>Math.abs(e.clientWidth/e.clientHeight-.75)<.01));
check('Desktop has no horizontal overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
for(const width of [390,768]){
 const mobile=await browser.newPage({viewport:{width,height:900}});
 await mobile.goto(origin+'/',{waitUntil:'networkidle'});
 await mobile.waitForFunction(()=>document.querySelector('#main')?.dataset.openingState==='ready');
 await mobile.waitForTimeout(900);
 await mobile.locator('.portrait-film').scrollIntoViewIfNeeded();await mobile.waitForTimeout(800);
 await mobile.screenshot({path:`qa/portrait-turn/portrait-${width}.png`});
 check(`Portrait fits at ${width}px`,await mobile.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 check(`Poster/video loads at ${width}px`,await mobile.locator('[data-scrub-video=portrait]').evaluate(e=>e.dataset.mediaState==='ready'));
 await mobile.close();
}
const reduced=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'reduce'});let requests=0;
reduced.on('request',r=>{if(r.url().includes('portrait-turn.mp4'))requests++});
await reduced.goto(origin+'/',{waitUntil:'networkidle'});
await reduced.locator('.portrait-film').scrollIntoViewIfNeeded();await reduced.waitForTimeout(700);
check('Reduced motion uses new still without video download',requests===0&&await reduced.locator('[data-scrub-video=portrait]').evaluate(e=>e.poster.includes('portrait-turn/poster.webp')));
await reduced.screenshot({path:'qa/portrait-turn/reduced-motion.png'});
const failed=await browser.newPage({viewport:{width:390,height:844}});
await failed.route('**/portrait-turn.mp4',r=>r.abort());
await failed.goto(origin+'/',{waitUntil:'networkidle'});
await failed.waitForFunction(()=>document.querySelector('#main')?.dataset.openingState==='ready');
check('Failed video keeps matching poster',await failed.locator('[data-scrub-video=portrait]').evaluate(e=>e.dataset.mediaState==='fallback'&&e.poster.includes('portrait-turn/poster.webp')));
check('No page errors',errors.length===0,errors);
writeFileSync('qa/portrait-turn/results.json',JSON.stringify(results,null,2));
console.log(JSON.stringify(results,null,2));await browser.close();if(results.some(r=>!r.pass))process.exitCode=1;

